#!/usr/bin/env python3
"""Render docs/SKILL_CATALOG.md and the domain table in docs/LIBRARY.md from machine/library.json."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIBRARY = ROOT / 'machine' / 'library.json'
CATALOG = ROOT / 'docs' / 'SKILL_CATALOG.md'
GUIDE = ROOT / 'docs' / 'LIBRARY.md'
BEGIN = '<!-- library:domains:begin (generated by scripts/build_catalog.py) -->'
END = '<!-- library:domains:end -->'


def load() -> dict:
    return json.loads(LIBRARY.read_text(encoding='utf-8'))


def render_catalog(library: dict) -> str:
    lines = [
        '# Skill Catalog',
        '',
        '<!-- Generated by scripts/build_catalog.py from machine/library.json. Edit the JSON, not this file. -->',
        '',
        'Every skill, shelved by domain and lane. The machine-readable catalog is '
        '[`machine/library.json`](../machine/library.json); the reading guide is [`LIBRARY.md`](LIBRARY.md).',
        '',
    ]
    for domain in library['domains']:
        lines += [f"## {domain['code']}. {domain['name']}", '', f"*{domain['question']}*", '']
        for lane in domain['lanes']:
            lines += [f"### {lane['code']} {lane['name']}", '']
            for entry in lane['skills']:
                lines.append(
                    f"- `{entry['call']}` **[`{entry['name']}`](../{entry['path']})** — {entry['tagline']}"
                )
            lines.append('')
    return '\n'.join(lines).rstrip() + '\n'


def render_domain_table(library: dict) -> str:
    rows = ['| Domain | The question it answers | Lanes |', '|---|---|---|']
    for domain in library['domains']:
        lanes = ' · '.join(f"{lane['code']} {lane['name']}" for lane in domain['lanes'])
        rows.append(f"| **{domain['code']}. {domain['name']}** | {domain['question']} | {lanes} |")
    return '\n'.join(rows)


def render_guide(library: dict, current: str) -> str:
    if BEGIN not in current or END not in current:
        raise SystemExit('docs/LIBRARY.md is missing the generated domain-table markers')
    head, rest = current.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f'{head}{BEGIN}\n{render_domain_table(library)}\n{END}{tail}'


def main() -> None:
    library = load()
    CATALOG.write_text(render_catalog(library), encoding='utf-8')
    GUIDE.write_text(render_guide(library, GUIDE.read_text(encoding='utf-8')), encoding='utf-8')
    print('catalog built from machine/library.json')


if __name__ == '__main__':
    sys.exit(main())
